BEGIN;

CREATE TABLE testimonials (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id  BIGINT        NOT NULL,
    rating       INTEGER       NOT NULL,
    message      VARCHAR(1000) NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    reviewed_at  TIMESTAMPTZ,

    created_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   BIGINT,
    updated_by   BIGINT,

    CONSTRAINT fk_testimonials_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_testimonials_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_testimonials_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,

    -- One per customer: resubmitting edits it rather than adding another.
    CONSTRAINT uq_testimonials_customer UNIQUE (customer_id),

    CONSTRAINT chk_testimonials_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT chk_testimonials_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    -- A reviewed row has a review time and a pending one does not.
    CONSTRAINT chk_testimonials_reviewed CHECK ((status = 'PENDING') = (reviewed_at IS NULL))
);

-- The storefront reads "approved, most recently approved first"; the back office filters by status.
CREATE INDEX idx_testimonials_status_reviewed
    ON testimonials (status, reviewed_at DESC);

CREATE TRIGGER trg_testimonials_set_updated_at
    BEFORE UPDATE ON testimonials
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
